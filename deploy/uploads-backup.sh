#!/usr/bin/env bash
# ============================================================
# Karimoff — атомарный снимок каталога пользовательских загрузок.
# Запускается systemd-юнитом karimoff-backup.service (ExecStartPost)
# сразу после WAL-safe копии БД (таймер 03:30).
#
# Схема: временный каталог (*.tmp) -> rsync -> проверка коллизии ->
# mv (атомарная публикация) -> touch (mtime = время публикации) ->
# ротация (не более KEEP завершённых снимков).
#
# Ошибки пишутся в stderr (попадают в journald) и завершают скрипт с
# rc != 0: systemd помечает job failed. Предыдущие снимки при любой
# ошибке остаются нетронутыми; ротация запускается только после
# успешной публикации нового снимка.
#
# Формат имени снимка совпадает с копиями БД (ISO, ':' и '.' -> '-'),
# поэтому снимок БД и снимок uploads одного прогона сопоставимы по
# времени для согласованного восстановления.
#
# UPLOADS_SRC / UPLOADS_BACKUP_DIR — тестовые крючки; по умолчанию
# используются боевые пути.
# ============================================================
set -u
umask 027

SRC="${UPLOADS_SRC:-/opt/karimoff/uploads}"
BASE="${UPLOADS_BACKUP_DIR:-/var/backups/karimoff}"
KEEP=14

fail() { echo "uploads-backup: $*" >&2; exit 1; }

command -v rsync >/dev/null 2>&1 || fail "rsync не установлен"
[ -d "$SRC" ] || fail "каталог ${SRC} отсутствует — снимок не создаётся"

# Метка времени — в том же формате, что и копии БД. node гарантированно
# присутствует (тот же рантайм, что и ExecStart бэкапа БД).
# Тестовый хук: UPLOADS_TS задаёт метку вручную (для детерминированных тестов).
if [ -n "${UPLOADS_TS:-}" ]; then
  TS="$UPLOADS_TS"
else
  TS="$(node -e 'process.stdout.write(new Date().toISOString().replace(/[:.]/g,"-"))')" \
    || fail "не удалось получить метку времени (node)"
fi

SNAP="${BASE}/uploads-snap-${TS}"
TMP="${SNAP}.tmp"

# Удаляем только остатки незавершённых временных каталогов от прошлых
# аварийных прогонов (файловый снимок публикуется исключительно через mv,
# каталог *.tmp никогда не считается валидным снимком).
rm -rf "${BASE}"/uploads-snap-*.tmp 2>/dev/null || true

mkdir "${TMP}" || fail "не создан временный каталог ${TMP} (права или диск)"

if ! rsync -a --delete "${SRC}/" "${TMP}/"; then
  rm -rf "${TMP}"
  fail "rsync завершился с ошибкой — снимок отменён, предыдущие копии не затронуты"
fi

if [ -e "${SNAP}" ]; then
  rm -rf "${TMP}"
  fail "снимок ${SNAP} уже существует — не перезаписываем"
fi

if ! mv "${TMP}" "${SNAP}"; then
  rm -rf "${TMP}"
  fail "публикация (mv) не удалась — предыдущие снимки не затронуты"
fi

# rsync -a переносит mtime источника; без touch свежий снимок мог бы
# отсортироваться ротацией как «старый» и быть удалённым первым.
touch "${SNAP}" || fail "не удалось обновить mtime снимка"

# Ротация: только завершённые снимки (-d — перечисляет сами каталоги,
# grep отбрасывает гипотетические *.tmp), максимум KEEP штук.
ls -1dt "${BASE}"/uploads-snap-* 2>/dev/null \
  | grep -v '\.tmp$' \
  | tail -n +"$((KEEP + 1))" \
  | xargs -r rm -rf
rc=$?
[ "$rc" -eq 0 ] || fail "ротация завершилась с ошибкой (rc=${rc}); новый снимок ${SNAP} опубликован, ротация не завершена"

echo "uploads-backup: снимок ${SNAP} готов"
